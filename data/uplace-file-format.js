// 🌟 [업로드용] .you 파일의 base64 픽셀 ID 배열을 실제 RGBA 픽셀 버퍼로 복원
export function decodeYouPixels(base64Pixels, width, height) {
    const binary = atob(base64Pixels);
    const bytes = new Uint8Array(binary.length);
    for (let i = 0; i < binary.length; i++) bytes[i] = binary.charCodeAt(i);

    const idToRgb = new Map();
    uplaceFileFormatIds.forEach((id, idx) => idToRgb.set(id, uplaceFileFormatPalette[idx]));

    const pixelCount = width * height;
    const rgba = new Uint8ClampedArray(pixelCount * 4);
    for (let i = 0; i < pixelCount; i++) {
        const id = bytes[i] || 0;
        const p = i * 4;
        if (id === 0) continue; // 알파 0(투명)으로 초기화된 상태 그대로 둠

        const rgb = idToRgb.get(id);
        if (!rgb) continue; // 알 수 없는 ID는 투명 처리

        rgba[p] = rgb[0]; rgba[p + 1] = rgb[1]; rgba[p + 2] = rgb[2]; rgba[p + 3] = 255;
    }
    return rgba;
}
